export function formatRuUiValue(value: unknown): string {
  if (value === undefined || value === null || value === "") return "Нет данных";
  const source = String(value);
  return ruUiValues[source] ?? source;
}

export function formatRuDateTime(value: string | undefined, timeZone?: string): string {
  if (!value) return "Нет данных";
  const timestamp = Date.parse(value);
  if (!Number.isFinite(timestamp)) return value;
  return new Intl.DateTimeFormat("ru-RU", {
    dateStyle: "short",
    timeStyle: "medium",
    ...(timeZone ? { timeZone } : {}),
  }).format(timestamp);
}
